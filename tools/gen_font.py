#!/usr/bin/env python3
"""Generate a compact 8x16 bitmap font header from a TTF.

Usage: python3 tools/gen_font.py [font.ttf] [size] [out.h]
"""

import sys
from PIL import Image, ImageDraw, ImageFont

FONT = (
    sys.argv[1]
    if len(sys.argv) > 1
    else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
)
SIZE = int(sys.argv[2]) if len(sys.argv) > 2 else 14
OUT = sys.argv[3] if len(sys.argv) > 3 else "main/font8x16.h"

W, H = 8, 16
# 127 is a hand-drawn degree sign (the TTF has no printable glyph there).
FIRST, LAST = 32, 127

font = ImageFont.truetype(FONT, SIZE)
glyphs = []

for code in range(FIRST, LAST + 1):
    if code == 127:
        rows = [0] * H
        rows[3:7] = [0x0C, 0x12, 0x12, 0x0C]
        glyphs.append(rows)
        continue
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    ch = chr(code)
    # centre the glyph in the cell
    bbox = d.textbbox((0, 0), ch, font=font)
    gw = bbox[2] - bbox[0]
    gh = bbox[3] - bbox[1]
    x = max(0, (W - gw) // 2 - bbox[0])
    y = max(0, (H - gh) // 2 - bbox[1])
    d.text((x, y), ch, font=font, fill=255)
    rows = []
    for yy in range(H):
        bits = 0
        for xx in range(W):
            if img.getpixel((xx, yy)) > 110:
                bits |= 0x80 >> xx
        rows.append(bits)
    glyphs.append(rows)

# preview
preview = Image.new("RGB", (W * 48, H * 2), (0, 0, 0))
for i, rows in enumerate(glyphs):
    ox = (i % 48) * W
    oy = (i // 48) * H
    for yy, bits in enumerate(rows):
        for xx in range(W):
            if bits & (0x80 >> xx):
                preview.putpixel((ox + xx, oy + yy), (255, 255, 255))
preview = preview.resize((W * 48 * 3, H * 2 * 3), Image.NEAREST)
preview.save("/tmp/opencode/font_preview.png")

with open(OUT, "w") as f:
    f.write("/* Generated by tools/gen_font.py - do not edit. */\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("#define FONT8X16_W 8\n#define FONT8X16_H 16\n")
    f.write("#define FONT8X16_FIRST %d\n#define FONT8X16_LAST %d\n\n" % (FIRST, LAST))
    f.write("static const uint8_t font8x16[%d][16] = {\n" % len(glyphs))
    for i, rows in enumerate(glyphs):
        f.write(
            "    { "
            + ", ".join("0x%02x" % r for r in rows)
            + " }, /* %d */\n" % (FIRST + i)
        )
    f.write("};\n")

print("wrote", OUT, "glyphs:", len(glyphs))
